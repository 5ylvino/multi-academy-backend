"""Repository port for academics."""

from __future__ import annotations

from datetime import datetime
from typing import Protocol
from uuid import UUID

from app.domain.academics.sections import Section
from app.domain.academics.structure import AcademicSession, Enrolment, SchoolClass, Subject, Term


class AcademicsRepository(Protocol):
    async def add_session(self, session: AcademicSession) -> None: ...

    async def get_session(self, session_id: UUID) -> AcademicSession | None: ...

    async def list_sessions(self) -> list[AcademicSession]: ...

    async def add_term(self, term: Term) -> None: ...

    async def get_term(self, term_id: UUID) -> Term | None: ...

    async def list_terms(self, session_id: UUID) -> list[Term]: ...

    async def make_current(self, term: Term) -> None:
        """Mark this term and its session current, and every other term and session not current."""
        ...

    async def current_term(self) -> Term | None: ...

    async def add_class(self, school_class: SchoolClass) -> None: ...

    async def get_class(
        self, class_id: UUID, *, for_update: bool = False
    ) -> SchoolClass | None: ...

    async def save_class(self, school_class: SchoolClass) -> None: ...

    async def list_classes(
        self, *, level: str | None, include_inactive: bool
    ) -> list[SchoolClass]: ...

    async def class_code_exists(self, code: str) -> bool: ...

    async def add_subject(self, subject: Subject) -> None: ...

    async def get_subject(self, subject_id: UUID) -> Subject | None: ...

    async def list_subjects(self, *, level: str | None) -> list[Subject]: ...

    async def subject_code_exists(self, code: str, level: str) -> bool: ...

    async def link_subject(
        self, class_id: UUID, subject_id: UUID, teacher_id: UUID | None
    ) -> None: ...

    async def unlink_subject(self, class_id: UUID, subject_id: UUID) -> None: ...

    async def teaches_class(self, teacher_id: UUID, class_id: UUID) -> bool:
        """Class teacher of the class, or teacher of one of its subjects."""
        ...

    async def subject_teacher(self, class_id: UUID, subject_id: UUID) -> UUID | None:
        """Who teaches this subject in this class, if anyone is assigned."""
        ...

    async def subjects_taught(self, teacher_id: UUID) -> list[tuple[UUID, UUID]]:
        """(class, subject) pairs the person teaches."""
        ...

    async def class_subject_teachers(self, class_id: UUID) -> dict[UUID, UUID | None]:
        """Each subject the class takes, with its teacher."""
        ...

    async def class_of_student(self, student_id: UUID, session_id: UUID) -> UUID | None: ...

    async def classes_of_students(self, student_ids: set[UUID], session_id: UUID) -> set[UUID]:
        """Classes the students are actively enrolled in for the session."""
        ...

    async def classes_taught_by(self, teacher_id: UUID) -> set[UUID]:
        """Classes the person is class teacher of, or teaches a subject in."""
        ...

    async def add_enrolment(self, enrolment: Enrolment) -> None: ...

    async def active_enrolment(self, student_id: UUID, session_id: UUID) -> Enrolment | None: ...

    async def save_enrolment(self, enrolment: Enrolment) -> None: ...

    async def count_active_in_class(self, class_id: UUID, session_id: UUID) -> int: ...

    async def roster(self, class_id: UUID, session_id: UUID) -> list[Enrolment]: ...


class SectionRepository(Protocol):
    async def list_sections(self) -> list[Section]: ...

    async def get_section(self, section_id: UUID) -> Section | None: ...

    async def lock(self) -> None:
        """Serialises changes to the school's arrangement of sections and staff assignments."""
        ...

    async def save_arrangement(self, sections: list[Section], removed: list[UUID]) -> None:
        """Write every section and its levels, and delete the removed sections (their staff
        must have been moved first)."""
        ...

    async def sections_of(self, user_id: UUID) -> set[UUID]: ...

    async def per_section_roles(self) -> set[str]:
        """Service roles this school runs per section (the rest serve the whole school)."""
        ...

    async def set_per_section_roles(self, roles: set[str]) -> None: ...

    async def staff_of(self, section_id: UUID) -> set[UUID]: ...

    async def staff_sections(self, user_ids: set[UUID]) -> dict[UUID, set[UUID]]: ...

    async def assign(
        self, user_id: UUID, section_ids: set[UUID], *, by: UUID, now: datetime
    ) -> None:
        """Replace the person's sections with these."""
        ...

    async def release_staff(self, section_id: UUID) -> set[UUID]:
        """Remove everyone from the section and return who they were."""
        ...

    async def add_staff(
        self, section_ids: set[UUID], user_ids: set[UUID], *, by: UUID, now: datetime
    ) -> None: ...
